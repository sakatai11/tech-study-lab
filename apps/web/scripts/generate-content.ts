import { spawnSync } from 'node:child_process'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import matter from 'gray-matter'

import { type ContentBundle, type ParsedContentSourceFile, createContentBundle } from '@tsl/shared'

import { compileMarkdown, serializeMarkdownTree } from './compile-markdown'

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const repositoryRoot = join(scriptDirectory, '../../..')
const contentRoot = join(repositoryRoot, 'content')
const generatedContentPath = join(repositoryRoot, 'apps/web/src/lib/generated-content.ts')
const generatedMarkdownPath = join(repositoryRoot, 'apps/web/src/lib/generated-markdown.ts')

function collectContentFiles(directory: string, sourceRoot = directory): ParsedContentSourceFile[] {
  return readdirSync(directory, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name, 'en'))
    .flatMap((entry) => {
      const entryPath = join(directory, entry.name)

      if (entry.isDirectory()) {
        return collectContentFiles(entryPath, sourceRoot)
      }
      if (!entry.isFile() || !entry.name.endsWith('.md')) {
        return []
      }

      const relativePath = relative(sourceRoot, entryPath).split(sep).join('/')
      try {
        const parsed = matter(readFileSync(entryPath, 'utf8'))
        return [{ relativePath, frontmatter: parsed.data, body: parsed.content }]
      } catch (error) {
        const detail = error instanceof Error ? error.message : 'failed to parse frontmatter'
        throw new Error(`${relativePath}: ${detail}`)
      }
    })
}

export function createGeneratedContentModule(bundle: ContentBundle): string {
  return `// Generated by apps/web/scripts/generate-content.ts. Do not edit manually.\nimport 'server-only'\nimport type { ContentBundle } from '@tsl/shared'\n\nexport const bundledContent = ${JSON.stringify(bundle, null, 2)} satisfies ContentBundle\n`
}

async function compileBodies(
  entries: { key: string; body: string }[],
): Promise<Record<string, string>> {
  const compiled: Record<string, string> = {}
  for (const { key, body } of entries) {
    compiled[key] = serializeMarkdownTree(await compileMarkdown(body))
  }
  return compiled
}

export async function createGeneratedMarkdownModule(bundle: ContentBundle): Promise<string> {
  const lessons = await compileBodies(
    bundle.lessons.map(({ lessonId, body }) => ({ key: lessonId, body })),
  )
  const topics = await compileBodies(
    bundle.topics.map(({ relativePath, body }) => ({ key: relativePath, body })),
  )
  return `// Generated by apps/web/scripts/generate-content.ts. Do not edit manually.\nimport 'server-only'\n\nexport const lessonMarkdownTrees: Record<string, string> = ${JSON.stringify(lessons, null, 2)}\n\nexport const topicMarkdownTrees: Record<string, string> = ${JSON.stringify(topics, null, 2)}\n`
}

function formatGeneratedModule(path: string, source: string): string {
  const biomeBin = process.platform === 'win32' ? 'biome.cmd' : 'biome'
  const result = spawnSync(
    join(repositoryRoot, 'node_modules/.bin', biomeBin),
    ['format', '--stdin-file-path', path],
    { cwd: repositoryRoot, encoding: 'utf8', input: source, maxBuffer: 64 * 1024 * 1024 },
  )

  if (result.status !== 0) {
    throw new Error(result.stderr || 'failed to format generated content')
  }

  return result.stdout
}

export async function renderContentModules(): Promise<{ content: string; markdown: string }> {
  const bundle = createContentBundle(collectContentFiles(contentRoot))
  return {
    content: formatGeneratedModule(generatedContentPath, createGeneratedContentModule(bundle)),
    markdown: formatGeneratedModule(
      generatedMarkdownPath,
      await createGeneratedMarkdownModule(bundle),
    ),
  }
}

export async function generateContentModule(): Promise<void> {
  const { content, markdown } = await renderContentModules()
  writeFileSync(generatedContentPath, content, 'utf8')
  writeFileSync(generatedMarkdownPath, markdown, 'utf8')
}

export async function checkGeneratedContentModule(): Promise<void> {
  const { content, markdown } = await renderContentModules()

  if (
    readFileSync(generatedContentPath, 'utf8') !== content ||
    readFileSync(generatedMarkdownPath, 'utf8') !== markdown
  ) {
    throw new Error('generated content is stale; run pnpm content:generate')
  }
}

const entryPath = process.argv[1]
if (entryPath && import.meta.url === pathToFileURL(entryPath).href) {
  if (process.argv.includes('--check')) {
    await checkGeneratedContentModule()
  } else {
    await generateContentModule()
  }
}
